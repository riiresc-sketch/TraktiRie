function resolveIconKey(keyOrEmoji) {
  if (!keyOrEmoji) return 'default';
  const k = String(keyOrEmoji);
  if (ICONS[k]) return k;
  if (EMOJI_MAP[k]) return EMOJI_MAP[k];
  return 'default';
}

function svg(keyOrEmoji, className) {
  className = className || 'w-5 h-5';
  const key = resolveIconKey(keyOrEmoji);
  const path = ICONS[key] || ICONS.default;
  return '<svg class="' + className + '" fill="none" stroke="currentColor" viewBox="0 0 24 24" aria-hidden="true">' + path + '</svg>';
}

